// The gateway had a REST surface — auth, the generic capability bridge,
// webhook management — and nothing that described it. An integrator building
// against it had to read this package's source, and no tool (a client
// generator, a Swagger UI, a contract test) had anything to consume.
//
// This is deliberately a hand-built document, not one generated from
// `sannad.kernel.v1.Capabilities` via grpc-gateway's proto annotations. That
// proto describes one generic RPC — Call(capability, opaque bytes) — and a
// codegen'd REST projection of it would describe exactly that: one path
// with an opaque body. The actual REST surface has more shape than the proto
// does (typed auth payloads, per-field webhook endpoint schemas), and none of
// it changes when a module registers or exposes a new capability — a
// capability's own request and response shape is that module's contract to
// publish, not the kernel's to guess. So the document below is what the
// kernel itself can honestly describe: its own fixed endpoints, precisely,
// and the capability dispatch endpoint's request truthfully documented as
// what it is — a reference and an opaque JSON payload, exactly as the proto
// already states.
//
// This is intentionally not wired to update itself from RegisterAuthenticatedRoutes:
// entrypoint-registered routes are named by the entrypoint, not the kernel, so
// the kernel cannot describe their schemas either — the same reason capability
// payloads are opaque. An entrypoint wanting its own routes documented can
// merge its own OpenAPI fragment with this one; nothing here forecloses that.

