func operation(summary, description string, requestSchema map[string]any, responseDescription string, security []string) map[string]any {
	op := map[string]any{
		"summary":     summary,
		"description": description,
		"responses":   map[string]any{"200": response(responseDescription, nil)},
	}
	if requestSchema != nil {
		op["requestBody"] = map[string]any{
			"required": true,
			"content":  map[string]any{"application/json": map[string]any{"schema": requestSchema}},
		}
	}
	if len(security) > 0 {
		sec := make([]map[string][]string, len(security))
		for i, s := range security {
			sec[i] = map[string][]string{s: {}}
		}
		op["security"] = sec
	}
	return op
}

func response(description string, schema map[string]any) map[string]any {
	resp := map[string]any{"description": description}
	if schema != nil {
		resp["content"] = map[string]any{"application/json": map[string]any{"schema": schema}}
	}
	return resp
}

func schemaRef(name string) map[string]any {
	return map[string]any{"$ref": "#/components/schemas/" + name}
}

func objectSchema(fields map[string]string, required []string) map[string]any {
	props := make(map[string]any, len(fields))
	for name, kind := range fields {
		props[name] = map[string]any{"type": kind}
	}
	schema := map[string]any{"type": "object", "properties": props}
	if len(required) > 0 {
		schema["required"] = required
	}
	return schema
}

func pathParam(name, description string) map[string]any {
	return map[string]any{
		"name": name, "in": "path", "required": true,
		"description": description,
		"schema":      map[string]any{"type": "string"},
	}
}

// injectIDParam adds the {id} path parameter to every operation on a path
// that names one, so it is declared once here rather than repeated at every
// operation literal above.
func injectIDParam(path string, methods map[string]any) {
	if !pathHasIDParam(path) {
		return
	}
	for method, raw := range methods {
		op, ok := raw.(map[string]any)
		if !ok {
			continue
		}
		existing, _ := op["parameters"].([]map[string]any)
		op["parameters"] = append([]map[string]any{pathParam("id", "Resource ID")}, existing...)
		methods[method] = op
	}
}

func pathHasIDParam(path string) bool {
	return strings.Contains(path, "{id}")
}

// handleOpenAPI serves the document. Unauthenticated, like the health
// endpoints: a spec describing a REST surface is not itself the surface, and
// requiring a token to read API documentation is what sends an integrator to
// read source code instead.
func (app *App) handleOpenAPI(ctx *fiber.Ctx) error {
	return ctx.Status(fiber.StatusOK).JSON(app.openAPIDocument())
}
